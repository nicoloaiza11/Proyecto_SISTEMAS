-- Consulta A: Semáforo de Ocupación Diaria y Remanente por Planta
SELECT
    e.nombre AS planta_acopio,
    t.fecha_entrega,
    e.capacidad_diaria_kg AS tope_diario_kg,
    COALESCE(SUM(t.kilos_estimados) FILTER (WHERE t.estado <> 'CANCELADO'), 0) AS kilos_reservados,
    e.capacidad_diaria_kg - COALESCE(SUM(t.kilos_estimados) FILTER (WHERE t.estado <> 'CANCELADO'), 0) AS remanente_libre_kg,
    ROUND(
        (COALESCE(SUM(t.kilos_estimados) FILTER (WHERE t.estado <> 'CANCELADO'), 0)::numeric
        / NULLIF(e.capacidad_diaria_kg, 0)) * 100, 1
    ) AS porcentaje_ocupacion,
    CASE
        WHEN COALESCE(SUM(t.kilos_estimados) FILTER (WHERE t.estado <> 'CANCELADO'), 0) >= e.capacidad_diaria_kg THEN 'COMPLETO (100%)'
        WHEN COALESCE(SUM(t.kilos_estimados) FILTER (WHERE t.estado <> 'CANCELADO'), 0) >= (e.capacidad_diaria_kg * 0.80) THEN 'ALERTA (>=80%)'
        ELSE 'NORMAL (<80%)'
    END AS estado_semaforo
FROM public.turnos_empresaacopio e
LEFT JOIN public.turnos_turno t ON t.empresa_id = e.id
GROUP BY e.id, e.nombre, e.capacidad_diaria_kg, t.fecha_entrega
ORDER BY t.fecha_entrega DESC NULLS LAST, e.nombre;


-- Consulta B: Planilla Detallada de Playa, Trazabilidad de Recorrido y Liquidación (SAD)
SELECT
    t.codigo AS orden_ingreso,
    t.fecha_entrega,
    t.franja_horaria AS ventana_2hs,
    t.patente_vehiculo AS dominio,
    u.razon_social AS productor,
    e.nombre AS centro_acopio,
    t.kilos_estimados AS kg_reservados,
    t.kilos_reales AS kg_netos_bascula,
    (t.kilos_reales - t.kilos_estimados) AS diferencia_kg,
    t.clase_tabaco,
    t.precio_kg AS usd_por_kg,
    ROUND((COALESCE(t.kilos_reales, 0) * COALESCE(t.precio_kg, 0))::numeric, 2) AS liquidacion_usd,
    ROUND(EXTRACT(EPOCH FROM (t.hora_arribo_playa - t.hora_salida_origen)) / 60.0, 0) AS min_viaje_ruta,
    ROUND(EXTRACT(EPOCH FROM (t.hora_descarga - t.hora_arribo_playa)) / 60.0, 0) AS min_espera_planta,
    ROUND(EXTRACT(EPOCH FROM (t.hora_descarga - t.hora_salida_origen)) / 60.0, 0) AS min_ciclo_total,
    t.estado AS situacion_planta
FROM public.turnos_turno t
INNER JOIN public.accounts_customuser u ON u.id = t.productor_id
INNER JOIN public.turnos_empresaacopio e ON e.id = t.empresa_id
ORDER BY t.fecha_entrega DESC, t.franja_horaria ASC;


-- Consulta C: Tablero Gerencial SAD (Ganado, Perdido, Velocidad y Tiempos por Franja Horaria)
SELECT
    e.nombre AS planta_acopio,
    t.franja_horaria,
    COUNT(*) FILTER (WHERE t.estado = 'DESCARGADO') AS camiones_descargados,
    COALESCE(SUM(t.kilos_reales) FILTER (WHERE t.estado = 'DESCARGADO'), 0) AS kg_netos_ganados,
    ROUND(COALESCE(SUM(t.kilos_reales * t.precio_kg) FILTER (WHERE t.estado = 'DESCARGADO'), 0)::numeric, 2) AS facturacion_usd,
    COALESCE(SUM(GREATEST(t.kilos_estimados - t.kilos_reales, 0)) FILTER (WHERE t.estado = 'DESCARGADO'), 0) AS kg_perdidos_sobrerreserva,
    ROUND(AVG(EXTRACT(EPOCH FROM (t.hora_arribo_playa - t.hora_salida_origen)) / 60.0)::numeric, 1) AS prom_min_ruta,
    ROUND(AVG(EXTRACT(EPOCH FROM (t.hora_descarga - t.hora_arribo_playa)) / 60.0)::numeric, 1) AS prom_min_espera_planta
FROM public.turnos_turno t
INNER JOIN public.turnos_empresaacopio e ON e.id = t.empresa_id
GROUP BY e.nombre, t.franja_horaria
ORDER BY e.nombre, t.franja_horaria;


