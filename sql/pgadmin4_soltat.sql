-- Consulta A: Ocupación diaria y remanente por empresa (hoy).
-- Los turnos descargados ocupan sus kilos reales; el resto, los estimados.
SELECT
    e.nombre                                                    AS empresa,
    e.capacidad_diaria_kg                                       AS capacidad_kg,
    COALESCE(SUM(COALESCE(t.kilos_reales, t.kilos_estimados)), 0) AS ocupados_kg,
    e.capacidad_diaria_kg
      - COALESCE(SUM(COALESCE(t.kilos_reales, t.kilos_estimados)), 0) AS remanente_kg,
    ROUND(100.0 * COALESCE(SUM(COALESCE(t.kilos_reales, t.kilos_estimados)), 0)
          / NULLIF(e.capacidad_diaria_kg, 0), 1)                AS ocupacion_pct
FROM accounts_empresaacopio e
LEFT JOIN turnos_turno t
       ON t.empresa_id = e.usuario_ptr_id
      AND t.fecha_entrega = CURRENT_DATE
      AND t.estado <> 'CANCELADO'
WHERE e.activa
GROUP BY e.usuario_ptr_id, e.nombre, e.capacidad_diaria_kg
ORDER BY e.nombre;


-- Consulta B: Ocupación por franja horaria (hoy), contra la capacidad de cada franja.
SELECT
    e.nombre                                                      AS empresa,
    f.franja,
    COALESCE(SUM(COALESCE(t.kilos_reales, t.kilos_estimados)), 0) AS ocupados_kg,
    e.capacidad_franja_kg                                         AS capacidad_franja_kg
FROM accounts_empresaacopio e
CROSS JOIN (VALUES ('06:00 - 08:00'), ('08:00 - 10:00'), ('10:00 - 12:00'), ('12:00 - 14:00'),
                   ('14:00 - 16:00'), ('16:00 - 18:00'), ('18:00 - 20:00'), ('20:00 - 22:00')) AS f (franja)
LEFT JOIN turnos_turno t
       ON t.empresa_id = e.usuario_ptr_id
      AND t.franja_horaria = f.franja
      AND t.fecha_entrega = CURRENT_DATE
      AND t.estado <> 'CANCELADO'
WHERE e.activa
GROUP BY e.nombre, f.franja, e.capacidad_franja_kg
ORDER BY e.nombre, f.franja;


-- Consulta C: Planilla de garita y báscula del día (todas las empresas), con tiempo de espera.
SELECT
    t.franja_horaria,
    t.codigo,
    e.nombre                                                 AS empresa,
    COALESCE(NULLIF(TRIM(u.first_name || ' ' || u.last_name), ''), u.username) AS productor,
    u.cuit_dni,
    t.patente_vehiculo,
    t.corte_tabaco,
    t.kilos_estimados,
    t.kilos_reales,
    t.estado,
    t.hora_arribo_playa,
    t.hora_descarga,
    ROUND(EXTRACT(EPOCH FROM (t.hora_descarga - t.hora_arribo_playa)) / 60.0, 1) AS espera_min,
    c.precio                                                 AS precio_kg
FROM turnos_turno t
JOIN accounts_empresaacopio e ON e.usuario_ptr_id = t.empresa_id
JOIN accounts_usuario u       ON u.id = t.productor_id
LEFT JOIN turnos_comprobante c ON c.turno_id = t.id
WHERE t.fecha_entrega = CURRENT_DATE
  AND t.estado IN ('CONFIRMADO', 'EN_PLAYA', 'DESCARGADO')
ORDER BY t.franja_horaria, e.nombre;


-- Consulta D: Incumplimientos de los productores en los últimos 90 días
-- (modelo de premios y castigos; mismas reglas que turnos/services.py):
--   · No se presentó: CONFIRMADO con fecha pasada.
--   · Canceló un turno confirmado: CANCELADO que conserva su comprobante.
--   · Desvío de kilos mayor al 20 %.
-- Nivel: 0 = BUENO (desde 06:00), 1 = REGULAR (desde 12:00), 2 = MALO (desde 18:00),
--        3 o más = BLOQUEADO 30 días desde el último incumplimiento.
WITH incumplimientos AS (
    SELECT t.productor_id, LEAST(t.fecha_entrega, CURRENT_DATE) AS fecha
    FROM turnos_turno t
    LEFT JOIN turnos_comprobante c ON c.turno_id = t.id
    WHERE t.fecha_entrega >= CURRENT_DATE - 90
      AND (
            (t.estado = 'CONFIRMADO' AND t.fecha_entrega < CURRENT_DATE)
         OR (t.estado = 'CANCELADO' AND c.id IS NOT NULL)
         OR (t.estado = 'DESCARGADO'
             AND ABS(t.kilos_reales - t.kilos_estimados) > 0.20 * t.kilos_estimados)
      )
)
SELECT
    u.cuit_dni,
    COALESCE(NULLIF(TRIM(u.first_name || ' ' || u.last_name), ''), u.username) AS productor,
    COUNT(i.fecha)  AS incumplimientos,
    MAX(i.fecha)    AS ultimo_incumplimiento,
    CASE
        WHEN COUNT(i.fecha) = 0 THEN 'BUENO'
        WHEN COUNT(i.fecha) = 1 THEN 'REGULAR'
        WHEN COUNT(i.fecha) = 2 THEN 'MALO'
        WHEN CURRENT_DATE < MAX(i.fecha) + 30 THEN 'BLOQUEADO'
        ELSE 'MALO'
    END AS nivel
FROM accounts_productor p
JOIN accounts_usuario u ON u.id = p.usuario_ptr_id
LEFT JOIN incumplimientos i ON i.productor_id = p.usuario_ptr_id
GROUP BY u.cuit_dni, u.first_name, u.last_name, u.username
ORDER BY incumplimientos DESC, productor;


-- Consulta E: Cupo de temporada de cada productor por empresa (asignado vs. usado).
SELECT
    e.nombre                                    AS empresa,
    COALESCE(NULLIF(TRIM(u.first_name || ' ' || u.last_name), ''), u.username) AS productor,
    cp.cupo_maximo,
    COALESCE(uso.usados_kg, 0)                  AS usados_kg,
    cp.cupo_maximo - COALESCE(uso.usados_kg, 0) AS remanente_kg
FROM (
    SELECT c.productor_id, r.empresa_asignada_id AS empresa_id, SUM(c.cupo_maximo) AS cupo_maximo
    FROM turnos_cupoproductor c
    JOIN accounts_recorredor r ON r.usuario_ptr_id = c.recorredor_id
    GROUP BY c.productor_id, r.empresa_asignada_id
) cp
JOIN accounts_empresaacopio e ON e.usuario_ptr_id = cp.empresa_id
JOIN accounts_usuario u       ON u.id = cp.productor_id
LEFT JOIN (
    SELECT productor_id, empresa_id, SUM(COALESCE(kilos_reales, kilos_estimados)) AS usados_kg
    FROM turnos_turno
    WHERE estado <> 'CANCELADO'
    GROUP BY productor_id, empresa_id
) uso ON uso.productor_id = cp.productor_id AND uso.empresa_id = cp.empresa_id
ORDER BY e.nombre, productor;


